def normalizar(texto):
    sem_acentos = "".join(
        caractere for caractere in unicodedata.normalize("NFKD", texto.casefold())
        if not unicodedata.combining(caractere)
    )
    return " ".join(re.findall(r"\w+", sem_acentos))


